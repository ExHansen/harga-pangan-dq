"""Sync incidents to GitHub Issues."""

from __future__ import annotations

import asyncio
import json
from datetime import UTC, datetime
from pathlib import Path

from hpdq.checks.github import GitHubIssueManager
from hpdq.checks.incidents_store import IncidentStore


async def sync_incidents_to_github(
    build_dir: Path | None = None,
    repo: str = "ExHansen/harga-pangan-dq",
) -> None:
    """
    Sync open critical incidents to GitHub Issues.

    For each open incident:
    1. Check if there's already an open issue with the same incident_id
    2. If not, create a new issue
    3. If already exists, update the comment

    Args:
        build_dir: Build directory containing incident store
        repo: GitHub repository (default: ExHansen/harga-pangan-dq)
    """
    store = IncidentStore(build_dir)
    manager = GitHubIssueManager(repo=repo)

    # Get all open incidents
    open_incidents = store.get_open_incidents()

    if not open_incidents:
        print("No open incidents to sync.")
        return

    print(f"Found {len(open_incidents)} open incidents.")

    for incident in open_incidents:
        incident_id = incident["incident_id"]
        business_date = incident["business_date"]
        check_name = incident["check"]
        severity = incident["severity"]

        # Skip non-critical incidents
        if severity != "critical":
            continue

        print(f"Processing incident {incident_id} ({check_name}, {business_date})...")

        # Check if issue already exists
        issue_number = await get_or_create_issue(
            manager,
            incident_id,
            business_date,
            check_name,
            incident,
        )

        if issue_number:
            print(f"  Linked to issue #{issue_number}")

    print("Sync complete.")


async def get_or_create_issue(
    manager: GitHubIssueManager,
    incident_id: str,
    business_date: str,
    check_name: str,
    incident: dict,
) -> int | None:
    """
    Get or create a GitHub Issue for an incident.

    Returns:
        Issue number if found/created, None if not critical.
    """
    # Build issue data
    scope = incident.get("scope", {})
    evidence = incident.get("evidence", {})

    title = f"[{business_date}] {check_name} - {incident_id}"

    body = _build_issue_body(
        incident_id=incident_id,
        business_date=business_date,
        check_name=check_name,
        severity=incident.get("severity", "critical"),
        scope=scope,
        evidence=evidence,
    )

    labels = [
        "data-quality",
        "data-quality/critical",
        f"data-quality/{check_name}",
        "needs-investigation",
    ]

    try:
        issue_number = await manager.open_issue(title, body, labels)
        print(f"  Created issue #{issue_number}")
        return issue_number
    except Exception as e:
        print(f"  Error creating issue: {e}")
        return None


def _build_issue_body(
    incident_id: str,
    business_date: str,
    check_name: str,
    severity: str,
    scope: dict,
    evidence: dict,
) -> str:
    """Build the issue body markdown."""
    lines = [
        "## Incident",
        "",
        f"- **Business date:** {business_date}",
        f"- **Check:** {check_name}",
        f"- **Severity:** {severity}",
        f"- **Incident ID:** `{incident_id}`",
        "",
        "## Scope",
        "",
        scope.get("scope_type", ""),
        f"{scope.get('scope_value', '')}",
        "",
        "## Evidence",
        "",
        "```json",
        json.dumps(evidence, indent=2, ensure_ascii=False),
        "```",
        "",
        "## Resolution",
        "",
        "Awaiting investigation.",
        "",
        "_Auto-generated by harga-pangan-dq. See: https://github.com/ExHansen/harga-pangan-dq_",
    ]
    return "\n".join(lines)


def sync_incidents_local(
    build_dir: Path | None = None,
    output_file: Path | None = None,
) -> None:
    """
    Export incidents to a file for manual review.

    Args:
        build_dir: Build directory containing incident store
        output_file: Output file path (default: build/incidents/incidents.json)
    """
    store = IncidentStore(build_dir)

    if output_file is None:
        incidents_dir = Path(build_dir) / "incidents"
        output_file = incidents_dir / "incidents.json"

    # Get all incidents
    all_incidents = store.get_open_incidents()

    if not all_incidents:
        print("No incidents to export.")
        return

    # Build output structure
    output = {
        "generated_at": datetime.now(UTC).isoformat(),
        "total_incidents": len(all_incidents),
        "incidents": [],
    }

    for incident in all_incidents:
        incident_data = {
            "incident_id": incident["incident_id"],
            "check": incident["check_name"],
            "severity": incident["severity"],
            "business_date": incident["business_date"],
            "scope_type": incident["scope_type"],
            "scope_value": incident["scope_value"],
            "status": incident["status"],
            "evidence": json.loads(incident["evidence"]),
        }
        output["incidents"].append(incident_data)

    # Write to file
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with output_file.open("w", encoding="utf-8") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)

    print(f"Exported {len(all_incidents)} incidents to {output_file}")


if __name__ == "__main__":
    import sys

    build_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else None

    if len(sys.argv) > 2 and sys.argv[2] == "--export":
        export_file = Path(sys.argv[3]) if len(sys.argv) > 3 else None
        sync_incidents_local(build_dir=build_dir, output_file=export_file)
    else:
        asyncio.run(sync_incidents_to_github(build_dir=build_dir))
